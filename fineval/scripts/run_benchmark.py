"""
Run the full fineval benchmark: Real vs {AIL, GBM} on every metric.

End-to-end flow:

1. Load the three curated datasets through their loaders — real and
   AIL from the CurationPipeline output, GBM from the baseline
   generated by scripts/baseline_generation.py.
2. Preprocess each (real, synthetic) pair: log returns, overnight
   masking, conditional FFF deseasonalization.
3. Run the matched-N ticker bootstrap: per resample, draw ticker
   subsamples for real-A, real-B and each generator, extract every
   metric's features, and accumulate g_rr / g_sr distance arrays.
4. Normalize into [0, 1] similarity scores with 95% paired-bootstrap
   CIs, print the benchmark table, and save the tidy results CSV.

Run from the repository root (defaults take ~1 min per resample):

    uv run python -m fineval.scripts.run_benchmark
    uv run python -m fineval.scripts.run_benchmark --n-resamples 20
"""

import argparse
from pathlib import Path

import pandas as pd

from fineval.bootstrap import MatchedTickerBootstrap
from fineval.config import (
    M1_N_GRID,
    M1_TAIL_ALPHA,
    M1_TAIL_LAMBDA,
    M2_LAG_MAX,
    M2_LAG_MIN,
    M4_MIN_OBS,
    M4_SCALES,
    N_REGIME_QUINTILES,
    REGIME_WEIGHTS,
    ROLLING_VOL_MIN_PERIODS,
    ROLLING_VOL_WINDOW,
    SEED,
    TAIL_QUANTILE,
)
from fineval.data import CuratedParquetLoader, GBMBaselineLoader
from fineval.metrics import (
    AggregationalGaussianity,
    RegimeConditionalTails,
    UnconditionalHeavyTails,
    VolatilityClustering,
)
from fineval.preprocessing import PreprocessingPipeline

CURATED_DIR = Path(__file__).resolve().parent / "data" / "curated"
RESULTS_DIR = Path(__file__).resolve().parent / "results"

METRIC_LABELS = {
    "M1": "Unconditional heavy tails",
    "M2": "Volatility clustering",
    "M4": "Aggregational Gaussianity",
    "M6": "Regime-conditional tails",
}


def build_metrics() -> list:
    """All implemented metrics, parametrized from fineval.config."""
    return [
        UnconditionalHeavyTails(
            name="M1",
            n_grid=M1_N_GRID,
            tail_alpha=M1_TAIL_ALPHA,
            tail_lambda=M1_TAIL_LAMBDA,
        ),
        VolatilityClustering(name="M2", lag_min=M2_LAG_MIN, lag_max=M2_LAG_MAX),
        AggregationalGaussianity(name="M4", scales=M4_SCALES, min_obs=M4_MIN_OBS),
        RegimeConditionalTails(
            name="M6",
            window=ROLLING_VOL_WINDOW,
            min_periods=ROLLING_VOL_MIN_PERIODS,
            n_regimes=N_REGIME_QUINTILES,
            tail_quantile=TAIL_QUANTILE,
            regime_weights=REGIME_WEIGHTS,
        ),
    ]


def format_table(results: pd.DataFrame) -> str:
    """Render the tidy results as a markdown benchmark table."""
    generators = list(dict.fromkeys(results["generator"]))
    header = "| Metric | Stylized fact | " + " | ".join(generators) + " |"
    rule = "|---|---|" + "---|" * len(generators)
    lines = [header, rule]
    for metric in list(dict.fromkeys(results["metric"])):
        cells = []
        for gen in generators:
            row = results[(results["metric"] == metric) & (results["generator"] == gen)].iloc[0]
            cells.append(f"{row['score']:.3f} [{row['ci_low']:.3f}, {row['ci_high']:.3f}]")
        label = METRIC_LABELS.get(metric, metric)
        lines.append(f"| {metric} | {label} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the fineval benchmark table.")
    parser.add_argument("--n-resamples", type=int, default=100, help="bootstrap resamples B")
    parser.add_argument("--tickers-per-draw", type=int, default=200, help="tickers per subsample")
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    print("Loading curated datasets...")
    real = CuratedParquetLoader(
        parquet_path=str(CURATED_DIR / "real_prices.parquet"), name="Real", is_synthetic=False
    ).load()
    ail = CuratedParquetLoader(
        parquet_path=str(CURATED_DIR / "ail_prices.parquet"), name="AIL", is_synthetic=True
    ).load()
    gbm = GBMBaselineLoader(parquet_path=str(CURATED_DIR / "gbm_prices.parquet")).load()

    print("Preprocessing (log returns, overnight mask, conditional FFF)...")
    deseas_real = None
    synthetics = {}
    for dataset in (ail, gbm):
        pipeline = PreprocessingPipeline().run(real.prices, dataset.prices)
        synthetics[dataset.name] = pipeline.deseas_synthetic
        if deseas_real is None:
            deseas_real = pipeline.deseas_real

    engine = MatchedTickerBootstrap(
        metrics=build_metrics(),
        n_resamples=args.n_resamples,
        tickers_per_draw=args.tickers_per_draw,
        seed=args.seed,
    )
    results = engine.run(deseas_real, synthetics)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = RESULTS_DIR / "benchmark_results.csv"
    results.to_csv(csv_path, index=False)

    print(
        f"\nBenchmark (B={args.n_resamples}, {args.tickers_per_draw} tickers/draw, "
        f"seed={args.seed}; score = mean(g_rr) / (mean(g_rr) + mean(g_sr)), "
        f"95% paired-bootstrap CI):\n"
    )
    print(format_table(results))
    print(f"\nTidy results saved to: {csv_path}")


if __name__ == "__main__":
    main()
